import './globals.css'
import type { Metadata } from 'next'
import { Inter } from 'next/font/google'
import React from 'react'
import { Toaster } from '@/components/ui/toaster'
import { AuthProvider } from './hooks/useAuth'
import { UserProfile } from '@/types/UserProfile'
import { jwtDecode } from 'jwt-decode';
import { cookies } from 'next/headers';

const inter = Inter({ 
  subsets: ['latin'],
  display: 'swap',
})

export const metadata: Metadata = {
  title: 'Pawprints',
  description: 'Generated by create next app',
}

export default async function RootLayout({ children, }: {
  children: React.ReactNode
}) {

  const cookieStore = cookies();
  const APP_COOKIE_NAME = process.env.APP_COOKIE || 'pawcess';
  const token = (await cookieStore).get(APP_COOKIE_NAME)?.value || null;

  let initialUser: UserProfile | null = null;

  const apiUrl = process.env.API_URL || 'http://localhost:8000';
  const alwaysLoggedIn = process.env.ALWAYS_LOGGED_IN === 'true';

  return (
    <html lang="en">
      <head>
        {/* Inject API URL at runtime so client components never need a build-time env var */}
        <script dangerouslySetInnerHTML={{ __html: `window.__API_URL__ = ${JSON.stringify(apiUrl)}; window.__ALWAYS_LOGGED_IN__ = ${alwaysLoggedIn};` }} />
      </head>
      <body className={inter.className}>
        <AuthProvider>
          {children}
        </AuthProvider>
        <Toaster />
      </body>
    </html>
  )
}
